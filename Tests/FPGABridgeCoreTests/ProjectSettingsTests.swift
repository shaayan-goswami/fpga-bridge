import XCTest
@testable import FPGABridgeCore

final class ProjectSettingsTests: XCTestCase {
    func project(_ change: (inout ProjectSettings) -> Void = { _ in }) -> Project {
        var settings = ProjectSettings()
        change(&settings)
        return Project(name: "p", top: "top", part: "xc7a35tcpg236-1", sources: ["src"], constraints: [], settings: settings)
    }

    func script(_ change: (inout ProjectSettings) -> Void = { _ in }) -> [String] {
        project(change).buildScript(sources: ["src/top.v"], constraints: ["pins.xdc"]).split(separator: "\n").map(String.init)
    }

    // MARK: The default script

    func testWithDesignDataOffTheScriptIsExactlyTheOneThatAlwaysWasGenerated() {
        var off = ProjectSettings()
        off.collectDesignData = false
        let plain = Project(name: "p", top: "top", part: "xc7a35tcpg236-1", sources: ["src"], constraints: [], settings: off)
        XCTAssertEqual(plain.buildScript(sources: ["src/top.v"], constraints: ["pins.xdc"]), """
            # Generated by fpga-bridge. Overwritten on every build.
            file mkdir out
            read_verilog {src/top.v}
            read_xdc {pins.xdc}
            synth_design -top top -part xc7a35tcpg236-1
            opt_design
            place_design
            route_design
            report_timing_summary -file out/timing_summary.rpt
            report_utilization -file out/utilization.rpt
            write_bitstream -force out/top.bit

            """)
    }

    func testDefaultSettingsAddTheDesignDataStepsAndNothingElse() {
        let none = Project(name: "p", top: "top", part: "xc7a35tcpg236-1", sources: ["src"], constraints: [])
        let explicit = project()
        let a = none.buildScript(sources: ["src/top.v"], constraints: ["pins.xdc"])
        XCTAssertEqual(a, explicit.buildScript(sources: ["src/top.v"], constraints: ["pins.xdc"]), "no settings and default settings agree")
        XCTAssertTrue(ProjectSettings().isDefault)
        XCTAssertTrue(a.contains("proc fpgabridge_dump"))
        // Take the design-data lines out and what is left is the old script.
        let withoutDump = a.split(separator: "\n", omittingEmptySubsequences: false)
        let kept = withoutDump.drop { !$0.hasPrefix("read_verilog") }
            .filter { !$0.hasPrefix("fpgabridge_dump") && $0 != "close_design" && !$0.hasPrefix("synth_design -rtl") }
        let head = ["# Generated by fpga-bridge. Overwritten on every build.", "file mkdir out"]
        let old = (head + kept.map(String.init)).joined(separator: "\n")
        var off = ProjectSettings(); off.collectDesignData = false
        XCTAssertEqual(old, Project(name: "p", top: "top", part: "xc7a35tcpg236-1", sources: ["src"], constraints: [], settings: off)
            .buildScript(sources: ["src/top.v"], constraints: ["pins.xdc"]))
    }

    // MARK: Each setting

    func testSynthesisFlags() {
        XCTAssertTrue(script { $0.synthesis.directive = "AreaOptimized_high" }.contains("synth_design -top top -part xc7a35tcpg236-1 -directive AreaOptimized_high"))
        XCTAssertTrue(script { $0.synthesis.flattenHierarchy = .full }.contains("synth_design -top top -part xc7a35tcpg236-1 -flatten_hierarchy full"))
        XCTAssertTrue(script { $0.synthesis.fsmExtraction = .oneHot }.contains("synth_design -top top -part xc7a35tcpg236-1 -fsm_extraction one_hot"))
        XCTAssertTrue(script { $0.synthesis.retiming = true }.contains("synth_design -top top -part xc7a35tcpg236-1 -retiming"))
        XCTAssertTrue(script { $0.synthesis.resourceSharing = .off }.contains("synth_design -top top -part xc7a35tcpg236-1 -resource_sharing off"))
        XCTAssertTrue(script { $0.synthesis.keepEquivalentRegisters = true }.contains("synth_design -top top -part xc7a35tcpg236-1 -keep_equivalent_registers"))
        XCTAssertTrue(script { $0.synthesis.maxBlockRAM = 0; $0.synthesis.maxDSP = 4 }
            .contains("synth_design -top top -part xc7a35tcpg236-1 -max_bram 0 -max_dsp 4"), "zero is a real limit, not 'unset'")
        XCTAssertTrue(script { $0.synthesis.moreOptions = "-no_lc -shreg_min_size 5" }
            .contains("synth_design -top top -part xc7a35tcpg236-1 -no_lc -shreg_min_size 5"))
    }

    func testLanguageOptionsReachSynthesis() {
        let line = script {
            $0.language.defines = ["FAST", "LEVEL=3"]
            $0.language.generics = ["WIDTH=10"]
            $0.language.includeDirectories = ["inc", "more inc"]
        }.first { $0.hasPrefix("synth_design -top") }
        XCTAssertEqual(line, "synth_design -top top -part xc7a35tcpg236-1 -verilog_define FAST -verilog_define LEVEL=3 -generic WIDTH=10 -include_dirs {inc more inc}")
    }

    func testImplementationStepsAndDirectives() {
        let steps = script {
            $0.implementation.optDirective = "Explore"
            $0.implementation.placeDirective = "ExtraTimingOpt"
            $0.implementation.physOpt = true
            $0.implementation.physOptDirective = "AggressiveExplore"
            $0.implementation.routeDirective = "MoreGlobalIterations"
            $0.implementation.postRoutePhysOpt = true
        }.filter { ["opt", "place", "phys", "route"].contains(where: $0.hasPrefix) }
        XCTAssertEqual(steps, ["opt_design -directive Explore", "place_design -directive ExtraTimingOpt",
                               "phys_opt_design -directive AggressiveExplore", "route_design -directive MoreGlobalIterations",
                               "phys_opt_design -directive AggressiveExplore"], "phys_opt after place, and again after route")
    }

    func testPhysOptIsOffUnlessAsked() {
        XCTAssertFalse(script().contains { $0.hasPrefix("phys_opt") })
        XCTAssertFalse(script { $0.implementation.physOptDirective = "Explore" }.contains { $0.hasPrefix("phys_opt") }, "a directive alone doesn't turn it on")
    }

    func testBitstreamPropertiesGoBeforeWriteBitstream() {
        let lines = script {
            $0.bitstream.binFile = true
            $0.bitstream.compress = true
            $0.bitstream.configRate = 33
            $0.bitstream.spiBusWidth = 4
            $0.bitstream.unusedPin = .pullnone
        }
        let write = lines.firstIndex { $0.hasPrefix("write_bitstream") }!
        XCTAssertEqual(lines[(write - 4)...], [
            "set_property BITSTREAM.GENERAL.COMPRESS TRUE [current_design]",
            "set_property BITSTREAM.CONFIG.CONFIGRATE 33 [current_design]",
            "set_property BITSTREAM.CONFIG.SPI_BUSWIDTH 4 [current_design]",
            "set_property BITSTREAM.CONFIG.UNUSEDPIN Pullnone [current_design]",
            "write_bitstream -force -bin_file out/top.bit",
        ][...])
    }

    func testTheReportsAreAlwaysWrittenBeforeTheBitstream() {
        let lines = script { $0.bitstream.compress = true }
        let timing = lines.firstIndex { $0.hasPrefix("report_timing_summary") }!
        let util = lines.firstIndex { $0.hasPrefix("report_utilization") }!
        let write = lines.firstIndex { $0.hasPrefix("write_bitstream") }!
        XCTAssertTrue(timing < util && util < write, "a failing bitstream step must not lose the reports")
    }

    // MARK: Strategies

    func testStrategiesSetDirectivesAndAreRecognizedAgain() throws {
        var i = ProjectSettings.Implementation()
        XCTAssertEqual(i.matchingStrategy, "Vivado Implementation Defaults")
        let explore = try XCTUnwrap(ProjectSettings.Implementation.strategies.first { $0.name == "Performance_Explore" })
        i.apply(explore)
        XCTAssertEqual([i.optDirective, i.placeDirective, i.physOptDirective, i.routeDirective], ["Explore", "Explore", "Explore", "Explore"])
        XCTAssertTrue(i.physOpt)
        XCTAssertEqual(i.matchingStrategy, "Performance_Explore")
        i.routeDirective = "Quick"
        XCTAssertNil(i.matchingStrategy, "edited by hand: no longer a named strategy")
        i.apply(ProjectSettings.Implementation.strategies[0])
        XCTAssertEqual(i, ProjectSettings.Implementation(), "defaults reset everything")
        for strategy in ProjectSettings.Implementation.strategies {
            var s = ProjectSettings(); s.implementation.apply(strategy)
            XCTAssertNoThrow(try s.validate(), strategy.name)
        }
    }

    // MARK: Saving and loading

    func testMissingFieldsMeanDefaults() throws {
        let partial = #"{"synthesis": {"retiming": true}, "bitstream": {"configRate": 33}}"#
        let s = try JSONDecoder().decode(ProjectSettings.self, from: Data(partial.utf8))
        XCTAssertTrue(s.synthesis.retiming)
        XCTAssertEqual(s.synthesis.flattenHierarchy, .rebuilt)
        XCTAssertEqual(s.bitstream.configRate, 33)
        XCTAssertNil(s.bitstream.spiBusWidth)
        XCTAssertEqual(s.simulation, ProjectSettings.Simulation())
        XCTAssertEqual(try JSONDecoder().decode(ProjectSettings.self, from: Data("{}".utf8)), ProjectSettings())
    }

    func testSettingsRoundTripThroughTheProjectFile() throws {
        var settings = ProjectSettings()
        settings.language.defines = ["A=1"]
        settings.synthesis.maxDSP = 0
        settings.implementation.routeDirective = "Explore"
        settings.bitstream.spiBusWidth = 2
        settings.simulation.standard = .v2005
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("ps-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        try Project(name: "p", top: "t", part: "x", sources: ["a"], constraints: [], settings: settings).save(to: dir)
        XCTAssertEqual(try Project.load(from: dir).settings, settings)
    }

    func testAnOldProjectFileWithoutSettingsStillLoads() throws {
        let old = #"{"name":"p","top":"t","part":"xc7a35tcpg236-1","sources":["a"],"constraints":[]}"#
        let p = try JSONDecoder().decode(Project.self, from: Data(old.utf8))
        XCTAssertNil(p.settings)
    }

    func testAnUnknownChoiceIsAnErrorNotASilentDefault() {
        XCTAssertThrowsError(try JSONDecoder().decode(ProjectSettings.self, from: Data(#"{"synthesis":{"flattenHierarchy":"sideways"}}"#.utf8)))
    }

    func testCleanedTrimsAndDropsBlankRows() {
        var s = ProjectSettings()
        s.language.defines = ["  FAST ", "", "   "]
        s.language.generics = [" W=1"]
        s.language.includeDirectories = ["", "inc "]
        s.synthesis.moreOptions = "  -no_lc   -x  "
        s.simulation.runtimeArguments = " +a   +b "
        let c = s.cleaned()
        XCTAssertEqual(c.language.defines, ["FAST"])
        XCTAssertEqual(c.language.generics, ["W=1"])
        XCTAssertEqual(c.language.includeDirectories, ["inc"])
        XCTAssertEqual(c.synthesis.moreOptions, "-no_lc -x")
        XCTAssertEqual(c.simulation.runtimeArguments, "+a +b")
        XCTAssertNoThrow(try c.validate())
        XCTAssertEqual(ProjectSettings().cleaned(), ProjectSettings(), "defaults stay defaults")
    }

    func testTheFormChecksAgreeWithValidation() {
        XCTAssertTrue(ProjectSettings.isValidDefine("A=1") && ProjectSettings.isValidDefine("A"))
        XCTAssertFalse(ProjectSettings.isValidDefine("A B") || ProjectSettings.isValidDefine("1A") || ProjectSettings.isValidDefine("A="))
        XCTAssertTrue(ProjectSettings.isValidGeneric("W=8"))
        XCTAssertFalse(ProjectSettings.isValidGeneric("W"))
        XCTAssertTrue(ProjectSettings.isValidIncludeDirectory("src/headers"))
        XCTAssertFalse(ProjectSettings.isValidIncludeDirectory("../x") || ProjectSettings.isValidIncludeDirectory("/etc"))
        XCTAssertTrue(ProjectSettings.isValidOptionText("-no_lc -x 5"))
        XCTAssertFalse(ProjectSettings.isValidOptionText("[exec x]"))
    }

    // MARK: Validation: these reach a Tcl script on the build machine

    func testValuesThatCouldBeTclAreRefused() {
        let attacks = ["[exec rm -rf /]", "-x; exec cmd", "$env(HOME)", "a\nexec x", "{a}", "\"a\"", "-flag `x`", "a\\b", "x#y"]
        for attack in attacks {
            for (name, change) in [
                ("synthesis options", { (s: inout ProjectSettings) in s.synthesis.moreOptions = attack }),
                ("opt options", { $0.implementation.optMoreOptions = attack }),
                ("place options", { $0.implementation.placeMoreOptions = attack }),
                ("route options", { $0.implementation.routeMoreOptions = attack }),
                ("bitstream options", { $0.bitstream.moreOptions = attack }),
                ("define", { $0.language.defines = [attack] }),
                ("generic", { $0.language.generics = ["W=" + attack] }),
                ("include folder", { $0.language.includeDirectories = [attack] }),
            ] as [(String, (inout ProjectSettings) -> Void)] {
                var s = ProjectSettings(); change(&s)
                XCTAssertThrowsError(try s.validate(), "\(name): \(attack.debugDescription)")
            }
        }
    }

    func testOrdinaryValuesAreAccepted() {
        var s = ProjectSettings()
        s.language.defines = ["FAST", "LEVEL=3", "NAME=abc_1", "RATIO=1.5", "OFF=-1"]
        s.language.generics = ["WIDTH=16", "MODE=fast"]
        s.language.includeDirectories = ["inc", "src/headers", "my includes"]
        s.synthesis.moreOptions = "-shreg_min_size 5 -no_lc"
        s.implementation.routeMoreOptions = "-tns_cleanup"
        s.simulation.runtimeArguments = "+seed=5 +verbose"
        XCTAssertNoThrow(try s.validate())
    }

    func testPathsCannotLeaveTheProject() {
        for bad in ["../outside", "/etc", "a/../../b", ""] {
            var s = ProjectSettings(); s.language.includeDirectories = [bad]
            XCTAssertThrowsError(try s.validate(), bad)
        }
    }

    func testDirectivesAndNumbersAreChecked() {
        func invalid(_ change: (inout ProjectSettings) -> Void, _ message: String, file: StaticString = #filePath, line: UInt = #line) {
            var s = ProjectSettings(); change(&s)
            XCTAssertThrowsError(try s.validate(), message, file: file, line: line)
        }
        invalid({ $0.synthesis.directive = "Bogus" }, "synth directive")
        invalid({ $0.implementation.optDirective = "Bogus" }, "opt directive")
        invalid({ $0.implementation.placeDirective = "Bogus" }, "place directive")
        invalid({ $0.implementation.physOptDirective = "Bogus" }, "phys_opt directive")
        invalid({ $0.implementation.routeDirective = "Bogus" }, "route directive")
        invalid({ $0.synthesis.maxBlockRAM = -1 }, "negative max_bram")
        invalid({ $0.bitstream.configRate = 34 }, "config rate")
        invalid({ $0.bitstream.spiBusWidth = 3 }, "spi width")
        invalid({ $0.simulation.timeLimit = 0 }, "time limit")
        invalid({ $0.simulation.waveformDepth = 65 }, "depth")
        invalid({ $0.simulation.runtimeArguments = "-evil" }, "run args must be plusargs")
        invalid({ $0.language.defines = ["1BAD"] }, "macro names are identifiers")
        invalid({ $0.language.generics = ["NOVALUE"] }, "generics need a value")
    }

    func testAnInvalidProjectFileIsRefusedOnLoad() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("ps-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        let text = #"{"name":"p","top":"t","part":"x","sources":["a"],"constraints":[],"settings":{"synthesis":{"moreOptions":"[exec x]"}}}"#
        try text.write(to: dir.appendingPathComponent(Project.fileName), atomically: true, encoding: .utf8)
        XCTAssertThrowsError(try Project.load(from: dir)) { XCTAssertTrue($0.userMessage.contains("Invalid settings"), $0.userMessage) }
    }

    // MARK: Everything together

    /// The script the real Vivado 2025.2 accepted when it was run on the build machine (see the probe in the commit
    /// message): every option on at once.
    func testTheFullProbeScript() {
        var s = ProjectSettings()
        s.collectDesignData = false     // the probe ran before the design-data steps existed
        s.language.defines = ["FAST", "LEVEL=3"]; s.language.generics = ["WIDTH=10"]; s.language.includeDirectories = ["inc"]
        s.synthesis.flattenHierarchy = .full; s.synthesis.fsmExtraction = .oneHot; s.synthesis.retiming = true
        s.synthesis.resourceSharing = .off; s.synthesis.directive = "RuntimeOptimized"
        s.implementation.optDirective = "Explore"; s.implementation.placeDirective = "Explore"; s.implementation.physOpt = true
        s.implementation.physOptDirective = "Explore"; s.implementation.routeDirective = "Explore"; s.implementation.postRoutePhysOpt = true
        s.bitstream.binFile = true; s.bitstream.compress = true; s.bitstream.configRate = 33; s.bitstream.spiBusWidth = 4
        s.bitstream.unusedPin = .pullnone
        let p = Project(name: "probe", top: "probe", part: "xc7a35tcpg236-1", sources: [], constraints: [], settings: s)
        XCTAssertEqual(p.buildScript(sources: ["src/probe.v"], constraints: ["constraints/probe.xdc"]), """
            # Generated by fpga-bridge. Overwritten on every build.
            file mkdir out
            read_verilog {src/probe.v}
            read_xdc {constraints/probe.xdc}
            synth_design -top probe -part xc7a35tcpg236-1 -directive RuntimeOptimized -flatten_hierarchy full -fsm_extraction one_hot -retiming -resource_sharing off -verilog_define FAST -verilog_define LEVEL=3 -generic WIDTH=10 -include_dirs {inc}
            opt_design -directive Explore
            place_design -directive Explore
            phys_opt_design -directive Explore
            route_design -directive Explore
            phys_opt_design -directive Explore
            report_timing_summary -file out/timing_summary.rpt
            report_utilization -file out/utilization.rpt
            set_property BITSTREAM.GENERAL.COMPRESS TRUE [current_design]
            set_property BITSTREAM.CONFIG.CONFIGRATE 33 [current_design]
            set_property BITSTREAM.CONFIG.SPI_BUSWIDTH 4 [current_design]
            set_property BITSTREAM.CONFIG.UNUSEDPIN Pullnone [current_design]
            write_bitstream -force -bin_file out/probe.bit

            """)
    }
}

/// The simulation settings, against real Icarus Verilog when it is installed.
final class SimulationSettingsTests: XCTestCase {
    var root: URL!

    override func setUpWithError() throws {
        root = FileManager.default.temporaryDirectory.appendingPathComponent("ss-\(UUID().uuidString)")
        for dir in ["src", "tb", "inc"] { try FileManager.default.createDirectory(at: root.appendingPathComponent(dir), withIntermediateDirectories: true) }
        try "`define GREETING \"hello from the include file\"\n".write(to: root.appendingPathComponent("inc/greeting.vh"), atomically: true, encoding: .utf8)
        try "module dut(input clk, output reg [3:0] q); always @(posedge clk) q <= q + 1; initial q = 0; endmodule\n"
            .write(to: root.appendingPathComponent("src/dut.v"), atomically: true, encoding: .utf8)
        try """
        `include "greeting.vh"
        module tb;
            reg clk = 0; wire [3:0] q;
            dut u (.clk(clk), .q(q));
            always #5 clk = ~clk;
            integer seed = 0;
            initial begin
                `ifdef LOUD $display("LOUD is defined"); `endif
                $display(`GREETING);
                if ($test$plusargs("verbose")) $display("verbose on");
                if ($value$plusargs("seed=%d", seed)) $display("seed=%0d", seed);
                #50 $finish;
            end
        endmodule
        """.write(to: root.appendingPathComponent("tb/tb.v"), atomically: true, encoding: .utf8)
    }

    override func tearDownWithError() throws { try? FileManager.default.removeItem(at: root) }

    /// The testbench includes a header, so every project here names the include folder unless a test says otherwise.
    func project(_ change: (inout ProjectSettings) -> Void = { _ in }) -> Project {
        var s = ProjectSettings(); s.language.includeDirectories = ["inc"]; change(&s)
        return Project(name: "p", top: "dut", part: "x", sources: ["src"], constraints: [], simulationSources: ["tb"], settings: s)
    }

    func run(_ project: Project) throws -> (String, Simulator.Result, Simulator.Plan) {
        try XCTSkipUnless(Simulator.locate() != nil, "Icarus Verilog isn't installed")
        let plan = try Simulator.plan(project: project, root: root)
        let log = LogBox()
        let result = try Simulator.require().simulate(plan, stop: Shell.StopFlag(), output: { log.append($0) })
        return (log.value, result, plan)
    }

    func testTheFlagsAreBuiltFromTheSettings() throws {
        let plan = try Simulator.plan(project: project {
            $0.simulation.standard = .v2005; $0.simulation.allWarnings = true
            $0.language.defines = ["LOUD", "N=3"]; $0.language.includeDirectories = ["inc"]
            $0.simulation.runtimeArguments = "+seed=7 +verbose"; $0.simulation.timeLimit = 9
        }, root: root)
        XCTAssertEqual(plan.compileArguments.prefix(3), ["-g2005", "-s", "tb"])
        XCTAssertTrue(plan.compileArguments.contains("-Wall"))
        XCTAssertTrue(plan.compileArguments.contains("-DLOUD") && plan.compileArguments.contains("-DN=3"))
        XCTAssertTrue(plan.compileArguments.contains(root.appendingPathComponent("inc").path))
        XCTAssertEqual(Array(plan.runArguments.dropFirst()), ["+seed=7", "+verbose"])
        XCTAssertEqual(plan.timeLimit, 9)
    }

    func testDefaultsChangeNothing() throws {
        let plan = try Simulator.plan(project: project(), root: root)   // only the include folder the testbench needs
        XCTAssertEqual(plan.compileArguments.prefix(5), ["-g2012", "-s", "tb", "-s", "__fpgabridge_dump"])
        XCTAssertEqual(plan.runArguments, [plan.imagePath])
        XCTAssertEqual(plan.timeLimit, 120)
        XCTAssertTrue(plan.dumpModule.contains("$dumpvars(0, tb)"))
    }

    func testMacrosIncludeFoldersAndPlusargsReachTheRun() throws {
        let (log, result, _) = try run(project {
            $0.language.defines = ["LOUD"]; $0.language.includeDirectories = ["inc"]; $0.simulation.runtimeArguments = "+seed=7 +verbose"
        })
        XCTAssertTrue(result.succeeded, log)
        XCTAssertTrue(log.contains("LOUD is defined"), log)
        XCTAssertTrue(log.contains("hello from the include file"), log)
        XCTAssertTrue(log.contains("verbose on") && log.contains("seed=7"), log)
    }

    func testWithoutThoseSettingsNoneOfThatHappens() throws {
        let (log, _, _) = try run(project { $0.language.includeDirectories = ["inc"] })
        XCTAssertFalse(log.contains("LOUD is defined") || log.contains("verbose on") || log.contains("seed="), log)
    }

    func testTurningWaveformsOffLeavesNoFileAndSkipsTheDumpModule() throws {
        let (log, result, plan) = try run(project { $0.simulation.recordWaveform = false })
        XCTAssertTrue(result.succeeded, log)
        XCTAssertNil(result.waveform)
        XCTAssertFalse(plan.dumpsWaveform)
        XCTAssertFalse(log.contains("VCD info"), log)
    }

    func testTheWaveformDepthLimitsWhatIsRecorded() throws {
        // Both runs write the same file, so read the first before the second replaces it.
        let (_, all, _) = try run(project())
        let full = try Waveform.load(from: XCTUnwrap(all.waveform))
        let (_, top, _) = try run(project { $0.simulation.waveformDepth = 1 })
        let shallow = try Waveform.load(from: XCTUnwrap(top.waveform))
        XCTAssertTrue(full.signals.contains { $0.scope.contains("u") }, "depth 0 records the instance under the testbench")
        XCTAssertFalse(shallow.signals.contains { $0.scope.contains("u") }, "depth 1 stops at the testbench itself")
    }

    func testTheTimeLimitComesFromTheProject() throws {
        try XCTSkipUnless(Simulator.locate() != nil, "Icarus Verilog isn't installed")
        try "module tb; reg clk = 0; always #5 clk = ~clk; endmodule\n".write(to: root.appendingPathComponent("tb/tb.v"), atomically: true, encoding: .utf8)
        let plan = try Simulator.plan(project: project { $0.simulation.timeLimit = 1 }, root: root)
        let started = Date()
        let result = try Simulator.require().simulate(plan, stop: Shell.StopFlag(), output: { _ in })
        XCTAssertTrue(result.timedOut)
        XCTAssertLessThan(Date().timeIntervalSince(started), 10)
    }
}
